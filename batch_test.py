"""
batch_test.py — Parallel batch evaluation harness for the Text-to-SQL agent.

Reads questions from an Excel column, runs every question through the full
DRGC pipeline capturing all intermediate steps and timing, then writes an
enriched Excel file with one row per question.

Usage
─────
    # Minimal (auto-discovers the first text column with 'question' in its name)
    python batch_test.py questions.xlsx

    # Explicit column name
    python batch_test.py questions.xlsx --col "Question"

    # Parallelism + output path
    python batch_test.py questions.xlsx --col "Question" --workers 10 --out results.xlsx

    # Limit to first N rows (smoke test)
    python batch_test.py questions.xlsx --col "Question" --limit 20

    # Retry failed rows from a previous run
    python batch_test.py results.xlsx --col "Question" --retry-errors

Options
───────
    --col           Column name that contains the questions  [default: auto-detect]
    --workers       Number of parallel threads               [default: 5]
    --out           Output Excel file path                   [default: <input>_results_<ts>.xlsx]
    --limit         Only run the first N questions           [default: all]
    --retry-errors  Re-run only rows where status == 'error' in a previous result file
    --log-level     Logging verbosity: DEBUG | INFO | WARNING | ERROR  [default: WARNING]
    --no-warmup     Skip the explicit cache-warmup barrier (first queries may be slower)

Output columns
──────────────
    question_no          Row index (1-based)
    question             Original question text
    status               success | error | clarification | non_data
    intent               Classified routing intent
    plan                 Logical decomposition plan
    schema_categories    Schema category groups selected by planner
    few_shot_count       Number of few-shot examples injected
    sql_query            Final SQL query (after filter corrections)
    filter_corrections   Summary of filter value corrections made
    validation_passed    Whether rule-based SQL validation passed
    validation_issues    Validation failure messages (if any)
    sql_corrections      Number of SQL self-correction iterations
    execution_time_ms    SQL execution time (database only)
    result_row_count     Number of rows returned by the query
    llm_answer           Natural-language answer generated by the responder
    total_time_s         End-to-end wall-clock time in seconds
    error                Error message (if status == 'error')
    steps_timeline       Human-readable step-by-step timeline
    steps_json           Machine-readable JSON of all steps (for programmatic use)
"""

