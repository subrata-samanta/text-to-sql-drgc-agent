# ─────────────────────────────────────────────────────────────────────────────

def main() -> None:
    # ── Output path ───────────────────────────────────────────────────────────
    if _args.out:
        out_path = _args.out
    else:
        stem     = Path(_args.input).stem
        out_path = str(Path(_args.input).parent / f"{stem}_results_{_ts_str}.xlsx")

    # ── Load questions ────────────────────────────────────────────────────────
    try:
        pairs, _ = _load_questions(
            _args.input, _args.col, _args.limit, _args.retry_errors
        )
    except ValueError as exc:
        tqdm.write(f"❌  {exc}")
        sys.exit(1)

    if not pairs:
        tqdm.write("⚠   No questions to run.")
        sys.exit(0)

    # ── Warmup ────────────────────────────────────────────────────────────────
    if not _args.no_warmup:
        _warmup()

    # ── Progress bar setup ────────────────────────────────────────────────────
    _icon = {"success": "✅", "error": "❌", "clarification": "💬", "non_data": "💬"}
    counts = {"✅": 0, "❌": 0, "💬": 0}

    tqdm.write(
        f"\n🚀  {len(pairs)} questions | {_args.workers} worker(s) | output → {out_path}\n"
    )

    bar = tqdm(
        total=len(pairs),
        desc="Running",
        unit="q",
        dynamic_ncols=True,
        file=sys.stdout,
        bar_format="{l_bar}{bar}| {n_fmt}/{total_fmt} [{elapsed}<{remaining}, {rate_fmt}] {postfix}",
        colour="cyan",
    )
    bar.set_postfix_str("✅ 0  ❌ 0  💬 0")

    # ── Parallel execution ────────────────────────────────────────────────────
    results: List[Dict] = [{}] * len(pairs)
    wall_start = time.time()
    done = 0

    with ThreadPoolExecutor(max_workers=_args.workers) as pool:
        future_to_idx = {
            pool.submit(_run_one, row_no, question): idx
            for idx, (row_no, question) in enumerate(pairs)
        }

        for future in as_completed(future_to_idx):
            idx = future_to_idx[future]
            try:
                row_result = future.result()
            except Exception as exc:
                row_no, question = pairs[idx]
                row_result = {
                    "question_no": row_no,
                    "question":    question,
                    "status":      "error",
                    "error":       f"Thread error: {exc}",
                    "total_time_s": round(time.time() - wall_start, 2),
                    **{k: "" for k in _OUTPUT_COLUMNS if k not in
                       ("question_no", "question", "status", "error", "total_time_s")},
                }

            results[idx] = row_result
            done += 1

            # Update progress bar
            icon = _icon.get(row_result.get("status", ""), "❌")
            counts[icon] = counts.get(icon, 0) + 1
            t_s  = row_result.get("total_time_s", "?")
            q_no = row_result.get("question_no", "?")
            bar.set_postfix_str(
                f"✅ {counts['✅']}  ❌ {counts['❌']}  💬 {counts['💬']}  "
                f"│ last Q#{q_no} {icon} {t_s}s"
            )
            bar.update(1)

            # Checkpoint every 50
            if done % 50 == 0:
                ckpt = out_path + ".checkpoint.xlsx"
                _save_results([r for r in results if r], ckpt)
                bar.write(f"💾  Checkpoint ({done}/{len(pairs)}) → {ckpt}")

    bar.close()

    # ── Final save ────────────────────────────────────────────────────────────
    total_wall = time.time() - wall_start
    results.sort(key=lambda r: r.get("question_no", 0))
    _save_results(results, out_path)
    _print_summary(results, total_wall)


if __name__ == "__main__":
    main()
