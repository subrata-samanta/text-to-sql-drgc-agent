def _warmup() -> None:
    """Wait for filter-resolver value cache to be ready."""
    if _CACHE_READY_EVENT.is_set():
        tqdm.write("✅  Value cache already warm")
        return
    bar = tqdm(
        total=1, desc="Cache warmup",
        bar_format="{desc}: {elapsed}",
        leave=False, file=sys.stdout, dynamic_ncols=True,
    )
    _t = time.time()
    _CACHE_READY_EVENT.wait()
    bar.close()
    tqdm.write(f"✅  Value cache ready  ({(time.time()-_t)*1000:.0f} ms)")


