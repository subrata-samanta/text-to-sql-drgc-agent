def _load_questions(
    xlsx_path: str,
    col: Optional[str],
    limit: Optional[int],
    retry_errors: bool,
) -> Tuple[List[Tuple[int, str]], pd.DataFrame]:
    """Load questions from Excel.  Returns [(row_no, question), ...] and the raw df."""
    df = pd.read_excel(xlsx_path, engine="openpyxl")

    # Auto-detect question column
    if col is None:
        candidates = [c for c in df.columns
                      if "question" in str(c).lower() or "query" in str(c).lower()]
        if candidates:
            col = candidates[0]
        elif len(df.columns) == 1:
            col = df.columns[0]
        else:
            raise ValueError(
                f"Cannot auto-detect question column in {xlsx_path}. "
                f"Available columns: {list(df.columns)}. "
                "Use --col to specify."
            )
    else:
        if col not in df.columns:
            raise ValueError(
                f"Column '{col}' not found. Available: {list(df.columns)}"
            )

    tqdm.write(f"📄  Input file  : {xlsx_path}")
    tqdm.write(f"🔑  Question col: '{col}'  ({len(df)} total rows)")

    # Filter to error-only rows for retry mode
    if retry_errors and "status" in df.columns:
        df = df[df["status"] == "error"].copy()
        tqdm.write(f"♻️   Retry mode  : {len(df)} error row(s) to re-run")

    # Drop blank questions
    df = df[df[col].astype(str).str.strip().ne("") & df[col].notna()].copy()
    df.reset_index(drop=True, inplace=True)

    if limit is not None:
        df = df.head(limit)
        tqdm.write(f"🔢  Limit        : first {limit} question(s)")

    pairs = [(i + 1, str(q).strip()) for i, q in enumerate(df[col])]
    tqdm.write(f"📊  Will run     : {len(pairs)} question(s)")
    return pairs, df


