def _run_one(row_no: int, question: str) -> Dict:
    """
    Execute one question through the full pipeline and return a flat result dict.

    Uses stream_agent_steps() so we can capture the per-node timeline with
    individual timing, while still collecting the complete final state.
    """
    result: Dict = {
        "question_no":         row_no,
        "question":            question,
        "status":              "error",
        "intent":              "",
        "plan":                "",
        "schema_categories":   "",
        "few_shot_count":      0,
        "sql_query":           "",
        "filter_corrections":  "",
        "validation_passed":   "",
        "validation_issues":   "",
        "sql_corrections":     0,
        "execution_time_ms":   "",
        "result_row_count":    "",
        "result_data_json":    "",
        "llm_answer":          "",
        "total_time_s":        "",
        "error":               "",
        "steps_timeline":      "",
        "steps_json":          "",
    }

    steps: List[Dict] = []
    wall_start = time.time()
    prev_ts = wall_start

    try:
        final_state: Optional[Dict] = None

        for event in stream_agent_steps(question, conversation_history=[]):
            now = time.time()
            if event["type"] == "step":
                node  = event["node"]
                label = event["label"]
                delta_ms = (now - prev_ts) * 1000
                prev_ts  = now

                # Collect a compact summary of what this node changed
                output = event.get("output") or {}
                changed_keys = [k for k in output if output[k] is not None
                                and k not in ("messages", "start_time")]

                steps.append({
                    "node":       node,
                    "label":      label,
                    "delta_ms":   round(delta_ms, 1),
                    "changed":    changed_keys,
                    "output_summary": _summarise_output(node, output),
                })

            elif event["type"] == "final":
                final_state = event["state"]

        wall_s = time.time() - wall_start

        if final_state is None:
            result["error"] = "Graph returned no final state"
            return result

        # ── Unpack final state ───────────────────────────────────────────────
        intent = final_state.get("intent") or ""
        error  = final_state.get("error")  or ""

        # Determine high-level status
        if error and not final_state.get("nl_response"):
            status = "error"
        elif final_state.get("needs_clarification"):
            status = "clarification"
        elif intent and intent not in ("data_query", "follow_up", "correction"):
            status = "non_data"
        else:
            status = "success"

        # Filter correction summary
        filter_log = final_state.get("filter_log") or []
        corrections = [
            f"{e['column']}='{e['sql_value']}' → {e.get('matched_column', e['column'])}='{e['db_match']}'"
            for e in filter_log
            if e.get("action") in ("corrected", "column_corrected", "business_rule")
        ]

        # Validation
        val_issues = final_state.get("validation_issues") or []

        # Result rows — normalise to list of dicts and keep all rows
        q_result = final_state.get("query_result")
        row_count = len(q_result) if isinstance(q_result, list) else ""

        # Serialise every row to JSON for storage
        result_data_json = ""
        if isinstance(q_result, list) and len(q_result) > 0:
            try:
                first = q_result[0]
                if isinstance(first, dict):
                    all_dicts = q_result
                elif hasattr(first, "_mapping"):
                    all_dicts = [dict(r._mapping) for r in q_result]
                elif hasattr(first, "_asdict"):
                    all_dicts = [r._asdict() for r in q_result]
                else:
                    all_dicts = [str(r) for r in q_result]
                result_data_json = json.dumps(all_dicts, ensure_ascii=False,
                                              default=str)
            except Exception as _e:
                result_data_json = f"[serialisation error: {_e}]"

        # Steps: human-readable timeline
        steps_tl = _build_timeline(steps, wall_s)

        result.update({
            "status":              status,
            "intent":              intent,
            "plan":                (final_state.get("plan") or "").replace("\n", " | "),
            "schema_categories":   ", ".join(final_state.get("relevant_schema_categories") or []),
            "few_shot_count":      len(final_state.get("few_shot_examples") or []),
            "sql_query":           final_state.get("sql_query") or "",
            "filter_corrections":  "; ".join(corrections) if corrections else "none",
            "validation_passed":   str(final_state.get("validation_passed") or ""),
            "validation_issues":   " | ".join(val_issues),
            "sql_corrections":     final_state.get("iterations") or 0,
            "execution_time_ms":   round(final_state.get("execution_time_ms") or 0, 1),
            "result_row_count":    row_count,
            "result_data_json":    result_data_json,
            "llm_answer":          final_state.get("nl_response")
                                   or final_state.get("direct_response") or "",
            "total_time_s":        round(wall_s, 2),
            "error":               error,
            "steps_timeline":      steps_tl,
            "steps_json":          json.dumps(steps, ensure_ascii=False),
        })

    except Exception as exc:
        result["error"]        = f"{type(exc).__name__}: {exc}"
        result["total_time_s"] = round(time.time() - wall_start, 2)
        result["steps_json"]   = json.dumps(steps, ensure_ascii=False)
        _loguru_logger.error(f"[Q#{row_no}] Unhandled error: {exc}\n{traceback.format_exc()}")

    return result


def _summarise_output(node: str, output: Dict) -> str:
    """Compact human-readable summary of what a node wrote to state."""
    if not output:
        return ""
    snippets: List[str] = []

    if node == "interaction":
        if output.get("intent"):
            snippets.append(f"intent={output['intent']}")
        rewritten = output.get("question")
        if rewritten:
            snippets.append(f"rewritten_q={rewritten[:60]!r}")

    elif node == "planner":
        if output.get("plan"):
            first_line = (output["plan"] or "").split("\n")[0][:80]
            snippets.append(f"plan={first_line!r}")
        cats = output.get("relevant_schema_categories")
        if cats:
            snippets.append(f"categories={cats}")

    elif node == "context_builder":
        n_ex = len(output.get("few_shot_examples") or [])
        if n_ex:
            snippets.append(f"{n_ex} few-shot example(s)")
        if output.get("schema_context"):
            snippets.append("schema_context ready")

    elif node == "generator":
        sql = output.get("sql_query") or ""
        if sql:
            snippets.append(f"sql={sql[:80].replace(chr(10), ' ')!r}")

    elif node == "filter_resolver":
        fl = output.get("filter_log") or []
        if fl:
            actions = [e.get("action", "?") for e in fl]
            snippets.append(f"filters={actions}")
        if output.get("needs_clarification"):
            snippets.append("⚠ needs_clarification")

    elif node == "sql_validator":
        snippets.append(
            "PASSED" if output.get("validation_passed") else
            f"FAILED: {output.get('validation_issues', [])}"
        )

    elif node == "executor":
        if output.get("error"):
            snippets.append(f"ERROR: {str(output['error'])[:80]}")
        elif output.get("result_preview"):
            snippets.append(f"rows={output.get('result_preview', '')[:60]!r}")

    elif node == "reflector":
        sql = output.get("sql_query") or ""
        if sql:
            snippets.append(f"fixed_sql={sql[:60].replace(chr(10), ' ')!r}")

    elif node == "responder":
        ans = output.get("nl_response") or ""
        if ans:
            snippets.append(f"answer={ans[:80]!r}")

    return "; ".join(snippets)


def _build_timeline(steps: List[Dict], total_s: float) -> str:
    """Render a compact human-readable step timeline string."""
    lines: List[str] = []
    for i, s in enumerate(steps, 1):
        summary = s["output_summary"]
        detail  = f" → {summary}" if summary else ""
        lines.append(
            f"Step {i:>2}  [{s['delta_ms']:>7.1f} ms]  {s['label']}{detail}"
        )
    lines.append(f"{'─'*60}")
    lines.append(f"Total: {total_s:.2f} s")
    return "\n".join(lines)





