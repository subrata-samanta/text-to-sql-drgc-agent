def _print_summary(results: List[Dict], total_wall: float) -> None:
    statuses   = [r.get("status", "error") for r in results]
    n_success  = statuses.count("success")
    n_error    = statuses.count("error")
    n_clarify  = statuses.count("clarification")
    n_non_data = statuses.count("non_data")

    times = [r["total_time_s"] for r in results if isinstance(r.get("total_time_s"), (int, float))]
    avg_t = sum(times) / len(times) if times else 0
    med_t = sorted(times)[len(times) // 2] if times else 0
    max_t = max(times) if times else 0

    tqdm.write("\n" + "═" * 62)
    tqdm.write("  BATCH SUMMARY")
    tqdm.write("═" * 62)
    tqdm.write(f"  Total          : {len(results)}")
    tqdm.write(f"  ✅ Success      : {n_success}")
    tqdm.write(f"  ❌ Error        : {n_error}")
    tqdm.write(f"  💬 Clarify/Non  : {n_clarify + n_non_data}")
    tqdm.write(f"  {'─'*40}")
    tqdm.write(f"  Wall-clock     : {total_wall:.1f} s  ({total_wall/60:.1f} min)")
    tqdm.write(f"  Throughput     : {len(results)/total_wall:.2f} q/s")
    tqdm.write(f"  Avg per q      : {avg_t:.2f} s")
    tqdm.write(f"  Median per q   : {med_t:.2f} s")
    tqdm.write(f"  Slowest q      : {max_t:.2f} s")
    if n_error:
        tqdm.write(f"\n  ⚠   First 3 errors:")
        for r in [r for r in results if r.get("status") == "error"][:3]:
            tqdm.write(f"       Q#{r['question_no']}: {str(r.get('error', ''))[:100]}")
    tqdm.write(f"  📋  Full logs  → {_log_path}")
    tqdm.write("═" * 62)


